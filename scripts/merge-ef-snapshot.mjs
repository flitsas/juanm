function extractBuildModel(designer) {
  const start = designer.indexOf("protected override void BuildTargetModel");
  const open = designer.indexOf("{", start);
  let depth = 0;
  for (let i = open; i < designer.length; i++) {
    if (designer[i] === "{") depth++;
    if (designer[i] === "}") {
      depth--;
      if (depth === 0) {
        return designer.slice(open + 1, i).trim();
      }
    }
  }
  throw new Error("BuildTargetModel not found");
}

function extractAfterIdentityColumns(buildModel) {
  const marker = "NpgsqlModelBuilderExtensions.UseIdentityByDefaultColumns(modelBuilder);";
  const start = buildModel.indexOf(marker);
  if (start === -1) {
    throw new Error("Identity columns marker not found");
  }
  return buildModel.slice(start + marker.length).trim();
}

function extractModuleEntities(buildModel) {
  const marker = 'modelBuilder.Entity("Gdc.Modules.';
  const start = buildModel.indexOf(marker);
  if (start === -1) {
    throw new Error("Module entities block not found");
  }
  return buildModel.slice(start).replace(/#pragma warning restore 612, 618\s*$/, "").trimEnd();
}

